-- ============================================================
-- 09. 키워드 기반 tier_rank 매핑 테이블 생성 + 기존 패턴 이관
--
-- *** 목적: "대표 모델 목록"에 없는 신상품이 나올 때마다 매번 큰 SQL을
-- 다시 짜지 않고, 이 테이블에 (키워드, tier_rank) 한 행만 추가하면 되게
-- 만든다. 순서(구체적 -> 일반적)를 사람이 신경 쓸 필요 없다 — 매칭 시
-- "가장 긴(=가장 구체적인) 키워드부터 자동으로 우선 적용"되기 때문이다
-- (예: "14600K"가 "14600"보다 길어서 항상 먼저 검사됨).
--
-- *** 앞으로 신상품 추가하는 법(DB 담당자용) ***
-- 1) 안 잡히는 상품명을 확인한다(10_apply_tier_keywords.sql 맨 아래
--    "매칭 안 된 상품" 조회로 확인).
-- 2) 이 상품에 맞는 키워드와 등급을 정해서 INSERT 한 줄 추가한다.
--    예: INSERT INTO cpu_tier_keywords (keyword, tier_rank) VALUES ('15600K', 27);
-- 3) 10_apply_tier_keywords.sql만 다시 실행한다(이 파일은 다시 실행할
--    필요 없음 — 테이블 구조와 기존 키워드는 그대로 유지됨).
-- ============================================================
USE dw_db;

CREATE TABLE IF NOT EXISTS cpu_tier_keywords (
    id INT AUTO_INCREMENT PRIMARY KEY,
    keyword VARCHAR(50) NOT NULL,
    tier_rank SMALLINT UNSIGNED NOT NULL,
    note VARCHAR(100) NULL,
    UNIQUE KEY uq_cpu_keyword (keyword)
);

CREATE TABLE IF NOT EXISTS gpu_tier_keywords (
    id INT AUTO_INCREMENT PRIMARY KEY,
    keyword VARCHAR(50) NOT NULL,
    tier_rank SMALLINT UNSIGNED NOT NULL,
    note VARCHAR(100) NULL,
    UNIQUE KEY uq_gpu_keyword (keyword)
);

